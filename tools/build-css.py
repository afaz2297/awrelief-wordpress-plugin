"""
Build assets/css/afazalif.css from the approved HTML design (html-design/assets/css/main.css).

Every component rule is scoped under `.afz` (the root class each widget and the global
UI render), so Elementor's own rules such as `.elementor img { height: auto }` cannot
override the design. Page-level rules (:root, html, body, scrollbars) stay global.

Usage: python tools/build-css.py <path to html-design main.css>
Then the plugin-only rules in assets/css/src/ (already scoped) are appended.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = pathlib.Path(sys.argv[1])
OUT = ROOT / 'assets/css/afazalif.css'
EXTRAS = [ROOT / 'assets/css/src/plugin.css', ROOT / 'assets/css/src/woo.css', ROOT / 'assets/css/src/pages.css']

GLOBAL_STARTS = (':root', 'html', '::', '*')
STATE_CLASSES = ('.rm', '.is-scrolling', '.lenis')  # live on <html>/<body>, outside .afz


def scope(sel):
    sel = sel.strip()
    if not sel or sel.startswith(GLOBAL_STARTS):
        return [sel]
    first, _, rest = sel.partition(' ')
    if first.startswith('body'):
        return [sel] if not rest else [f'{first} .afz {rest}']
    if first.startswith(STATE_CLASSES):
        return [sel] if not rest else [f'{first} .afz {rest}']
    if first == '.light':
        # .light sits on a section inside a widget, or on an Elementor container around widgets
        return [f'.afz {sel}', f'.light .afz {rest}'.strip() if rest else '.light .afz']
    return [f'.afz {sel}']


def transform(css):
    out, i, n = [], 0, len(css)
    while i < n:
        j = css.find('{', i)
        if j < 0:
            out.append(css[i:])
            break
        head = css[i:j]
        # find the matching close brace
        depth, k = 1, j + 1
        while depth and k < n:
            depth += {'{': 1, '}': -1}.get(css[k], 0)
            k += 1
        body = css[j + 1:k - 1]
        lead = head[:len(head) - len(head.lstrip())]
        h = head.strip()
        # comments in front of a rule stay with it
        comments = ''
        while h.startswith('/*'):
            end = h.find('*/') + 2
            comments += h[:end] + '\n'
            h = h[end:].strip()
        if h.startswith('@media') or h.startswith('@supports'):
            out.append(f'{lead}{comments}{h} {{{transform(body)}}}')
        elif h.startswith('@'):
            out.append(f'{lead}{comments}{h} {{{body}}}')
        else:
            sels = []
            for s in h.split(','):
                sels += scope(s)
            out.append(f'{lead}{comments}{", ".join(sels)} {{{body}}}')
        i = k
    return ''.join(out)


css = SRC.read_text(encoding='utf-8')
# assets the plugin ships itself
css = css.replace('url("../img/grain.png?v=20261101")', 'url("../img/grain.webp")')
# the founder LQIP becomes a per-image CSS variable written by the Story widget
css = re.sub(r'background: center 50% / cover url\(data:image/webp;base64,[^)]+\);',
             'background: center 50% / cover var(--lqip, none);', css)
# the basket drawer was `.cart` in the HTML design; WooCommerce's own add-to-basket form is `form.cart`
css = re.sub(r'\.cart(?![\w-])', '.cart-drawer', css)
css = css.replace('/* .gold-mask--emblem / --wordmark masks live in masks.css (inlined PNGs so file:// previews work) */\n', '')

built = '/* AWRELIEF design system — generated by tools/build-css.py from the approved HTML design. Do not edit by hand: edit the source or assets/css/src/*.css. */\n'
built += transform(css)
for extra in EXTRAS:
    built += f'\n\n/* ---------- {extra.relative_to(ROOT).as_posix()} ---------- */\n' + extra.read_text(encoding='utf-8')
OUT.write_text(built, encoding='utf-8')
print('wrote', OUT, len(built), 'bytes')
